import { execSync } from "child_process";
import { mkdirSync, writeFileSync } from "fs";
import { dirname } from "path";

const OUTPUT_FILE = "src/generated/build-info.ts";
const ISO_DATE_REGEX = /^\d{4}-\d{2}-\d{2}$/;
const DATE_OVERRIDE_ENV = "CONTENT_UPDATED_AT";

const getTodayInUtc = () => new Date().toISOString().slice(0, 10);

const getLastCommitDate = () => {
  const date = execSync("git log -1 --format=%cd --date=format:%Y-%m-%d", {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();

  if (!ISO_DATE_REGEX.test(date)) {
    throw new Error(`Unexpected git date format: "${date}"`);
  }

  return date;
};

const getConfiguredDate = () => {
  const configuredDate = process.env[DATE_OVERRIDE_ENV]?.trim();
  if (!configuredDate) {
    return null;
  }
  if (!ISO_DATE_REGEX.test(configuredDate)) {
    throw new Error(`${DATE_OVERRIDE_ENV} must use YYYY-MM-DD format, received "${configuredDate}".`);
  }
  return configuredDate;
};

const hasWorkingTreeChanges = () => {
  const status = execSync("git status --porcelain --untracked-files=all", {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();

  return status.length > 0;
};

const getContentUpdateDate = () => {
  const configuredDate = getConfiguredDate();
  if (configuredDate) {
    return { date: configuredDate, source: DATE_OVERRIDE_ENV };
  }
  if (hasWorkingTreeChanges()) {
    return { date: getTodayInUtc(), source: "working tree changes" };
  }
  return { date: getLastCommitDate(), source: "latest git commit" };
};

try {
  const { date, source } = getContentUpdateDate();
  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(
    OUTPUT_FILE,
    `// Auto-generated by generate-build-info.mjs\nexport const LAST_UPDATE = "${date}" as const;\n`,
    "utf8",
  );
  console.log(`Content update date injected (${OUTPUT_FILE}): ${date} (${source})`);
} catch (error) {
  const fallbackDate = getTodayInUtc();
  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(
    OUTPUT_FILE,
    `// Auto-generated by generate-build-info.mjs\nexport const LAST_UPDATE = "${fallbackDate}" as const;\n`,
    "utf8",
  );
  console.warn(
    `Could not read git history, falling back to ${fallbackDate}.`,
    error instanceof Error ? error.message : error,
  );
}
